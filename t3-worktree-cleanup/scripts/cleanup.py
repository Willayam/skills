#!/usr/bin/env python3
"""Unattended git worktree cleanup for a machine running T3 Code.

Dry run by default. With --apply it removes every agent worktree that passes
all the checks in judge() and holds the rest with a reason. It stops instead
of guessing when T3's database or the process list can't be read.
"""

import argparse
import json
import os
import re
import shutil
import socket
import sqlite3
import subprocess
import sys
import time
from pathlib import Path

HOME = Path.home()
DB = HOME / ".t3/userdata/statev2.sqlite"
# Folders where agent tools create worktrees. A repo's .claude/worktrees counts too.
# Worktrees anywhere else are someone's own checkout and are never removed.
WORKTREE_ROOTS = [
    HOME / ".t3/worktrees",
    HOME / ".codex/worktrees",
    HOME / ".cursor/worktrees",
    HOME / "conductor/workspaces",
]
REPO_PARENTS = [HOME / "Development"]
# Ignored paths that are rebuilt by an install or a build.
BUILD_DIRS = {
    "node_modules", ".pnpm-store", ".angular", ".next", ".turbo", ".vite", "dist",
    "build", "out", "target", "coverage", ".cache", ".parcel-cache", ".svelte-kit",
    ".vercel", ".expo", ".output", ".nuxt", "__pycache__", ".pytest_cache",
    ".mypy_cache", ".ruff_cache", ".venv", "venv", "Pods", "DerivedData", ".gradle",
    "playwright-report", "test-results", ".astro", "autogenerated",
}
BUILD_NAMES = {".DS_Store", ".eslintcache"}
BUILD_SUFFIXES = (".tsbuildinfo",)
# Build output under an ambiguous parent.
BUILD_PATHS = ("src-tauri/gen", ".wrangler/tmp", ".wrangler/state/v3/cache")
# Files in a worktree's git dir that mean a rebase, merge, or similar is paused.
UNFINISHED_OPS = (
    "rebase-merge", "rebase-apply", "sequencer", "MERGE_HEAD", "CHERRY_PICK_HEAD",
    "REVERT_HEAD", "BISECT_LOG",
)
# Ignored env files that worktree setup copies in from the main checkout.
ENV_PREFIXES = (".env", ".dev.vars")
# Ignored agent scratch, removed but named in the report. .wrangler/state is the
# local dev database wrangler dev seeds, which in an agent worktree is test data.
SCRATCH_DIRS = {".context"}
SCRATCH_PATHS = (".wrangler/state",)
ACTIVE_RUN_STATES = ("queued", "preparing", "starting", "running", "waiting")
RECENT_SECONDS = 24 * 3600


class Stop(Exception):
    """A check that can't run. Removing anything without it isn't safe."""


def run(args, cwd=None, timeout=60):
    try:
        p = subprocess.run(
            args, cwd=cwd, capture_output=True, text=True, timeout=timeout
        )
        return p.returncode, p.stdout, p.stderr
    except (subprocess.TimeoutExpired, FileNotFoundError, NotADirectoryError):
        return 1, "", "timed out or not found"


def git(path, *args, timeout=60):
    rc, out, _ = run(["git", "-C", str(path), *args], timeout=timeout)
    return rc, out


def retried(call):
    """One retry, so a short network drop doesn't hold a week's cleanup."""
    result = call()
    if result[0] != 0:
        time.sleep(30)
        result = call()
    return result


def real(path):
    return os.path.realpath(str(path))


def short(path):
    s = str(path)
    return "~" + s[len(str(HOME)) :] if s.startswith(str(HOME)) else s


def inside(path, parent):
    path, parent = str(path), str(parent)
    return path == parent or path.startswith(parent.rstrip("/") + "/")


def strictly_inside(path, parent):
    return inside(path, parent) and str(path) != str(parent)


def free_gb():
    return shutil.disk_usage(str(HOME)).free / 1e9


def size_of(path):
    rc, out, _ = run(["du", "-sk", str(path)], timeout=120)
    if rc != 0 or not out:
        return "?"
    kb = int(out.split()[0])
    return f"{kb / 1e6:.1f}G" if kb >= 1e5 else f"{kb / 1e3:.0f}M"


def t3_state():
    """Map real worktree path -> [(thread title, state)], plus T3 project roots."""
    if not DB.exists():
        raise Stop(f"{short(DB)} is missing, so T3 threads can't be checked.")
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True, timeout=30)
    try:
        roots = {
            real(r[0])
            for r in con.execute(
                "select workspace_root from projection_projects where deleted_at is null"
            )
        }
        marks = ",".join("?" * len(ACTIVE_RUN_STATES))
        running = {
            r[0]
            for r in con.execute(
                f"select distinct thread_id from orchestration_v2_projection_runs where status in ({marks})",
                ACTIVE_RUN_STATES,
            )
        }
        threads = {}
        for tid, title, wt, root, arch, deleted, settled, pinned in con.execute(
            """select thread_id, title,
                   json_extract(payload_json,'$.worktreePath'),
                   coalesce(json_extract(payload_json,'$.lineage.rootThreadId'), thread_id),
                   archived_at, deleted_at,
                   json_extract(payload_json,'$.settledAt'),
                   json_extract(payload_json,'$.pinnedAt')
               from orchestration_v2_projection_threads"""
        ):
            threads[tid] = dict(
                title=title, wt=wt, root=root, arch=arch, deleted=deleted,
                settled=settled, pinned=pinned,
            )
    finally:
        con.close()

    if not any(t["wt"] for t in threads.values()) and any((HOME / ".t3/worktrees").glob("*/*")):
        raise Stop("no T3 thread names a worktree, so the database format may have changed.")

    # A running delegated thread keeps its whole family in use.
    running_roots = {threads[t]["root"] for t in running if t in threads}
    uses = {}
    for tid, t in threads.items():
        if not t["wt"]:
            continue
        r = threads.get(t["root"])
        if tid in running or t["root"] in running_roots:
            state = "running"
        elif t["deleted"]:
            continue
        elif r is None:
            state = "open"  # parent thread unknown, so assume it is in use
        elif r["pinned"] or t["pinned"]:
            state = "pinned"
        elif r["deleted"]:
            continue
        elif r["arch"]:
            state = "archived"
        elif not r["settled"]:
            state = "open"
        else:
            state = "settled"
        title = r["title"] if r else t["title"]
        uses.setdefault(real(t["wt"]), []).append((title, state))
    return uses, roots


def process_cwds():
    rc, out, _ = run(["lsof", "-d", "cwd", "-Fn"], timeout=120)
    cwds = {real(l[1:]) for l in out.splitlines() if l.startswith("n")}
    if rc != 0 or not cwds:
        raise Stop("lsof failed, so busy worktrees can't be detected.")
    return cwds


def discover_repos(project_roots):
    """Map git common dir -> main checkout path."""
    candidates = set(project_roots)
    for parent in REPO_PARENTS:
        if parent.is_dir():
            candidates.update(str(p) for p in parent.iterdir() if (p / ".git").exists())
    for root in WORKTREE_ROOTS:
        if root.is_dir():
            candidates.update(str(p) for p in root.glob("*/*") if (p / ".git").exists())
    repos = {}
    for c in sorted(candidates):
        if not os.path.isdir(c):
            continue
        rc, out = git(c, "rev-parse", "--path-format=absolute", "--git-common-dir")
        if rc != 0 or not out.strip() or real(out.strip()) in repos:
            continue
        rc, wl = git(c, "worktree", "list", "--porcelain")
        first = next((l[9:] for l in wl.splitlines() if l.startswith("worktree ")), None)
        if rc == 0 and first:
            repos[real(out.strip())] = first
    return repos


def list_worktrees(repo):
    rc, out = git(repo, "worktree", "list", "--porcelain")
    items, cur = [], {}
    for line in out.splitlines() + [""]:
        if not line:
            if cur:
                items.append(cur)
            cur = {}
            continue
        key, _, val = line.partition(" ")
        cur[key] = val or True
    return items[1:]  # the first entry is the main checkout


def github_slug(repo):
    rc, out = git(repo, "remote", "get-url", "origin")
    m = re.search(r"github\.com[:/]([^/]+/[^/]+?)(?:\.git)?/?$", out.strip()) if rc == 0 else None
    return m.group(1) if m else None


def pr_states(repo, notes):
    slug = github_slug(repo)
    if not slug:
        return {}
    rc, out, _ = retried(lambda: run(
        ["gh", "pr", "list", "--repo", slug, "--state", "all", "--limit", "400",
         "--json", "number,state,headRefName,headRefOid,isCrossRepository"],
        timeout=90,
    ))
    try:
        found = json.loads(out) if rc == 0 else None
    except ValueError:
        found = None
    if found is None:
        notes.append(f"Couldn't list PRs for {slug}, so no PR counts as done there.")
        return None
    prs = {}
    for pr in found:
        if not pr.get("isCrossRepository"):  # a fork can reuse a branch name
            prs.setdefault(pr["headRefName"], pr)  # newest first
    return prs


def refresh_default_branch(repo, notes):
    """Fetch and return origin/<default branch>, or None when that can't be trusted."""
    if git(repo, "remote", "get-url", "origin")[0] != 0:
        return None
    if retried(lambda: git(repo, "fetch", "origin", "--quiet", timeout=180))[0] != 0:
        notes.append(f"Fetch failed for {short(repo)}, so nothing there counts as merged.")
        return None
    rc, out = retried(lambda: git(repo, "ls-remote", "--symref", "origin", "HEAD", timeout=60))
    m = re.search(r"^ref: refs/heads/(\S+)\s+HEAD", out, re.M) if rc == 0 else None
    if not m:
        notes.append(f"Couldn't read the default branch of {short(repo)}, so nothing there counts as merged.")
        return None
    ref = f"origin/{m.group(1)}"
    return ref if git(repo, "rev-parse", "--verify", "--quiet", ref)[0] == 0 else None


def last_activity(path):
    """Newest of worktree creation and its last checkout or commit."""
    rc, out = git(path, "rev-parse", "--absolute-git-dir")
    if rc != 0:
        return time.time()
    admin = Path(out.strip())
    stamps = [
        f.stat().st_mtime for f in (admin / "gitdir", admin / "logs/HEAD") if f.exists()
    ]
    return max(stamps, default=time.time())


def tracked_edits(path):
    rc, out = git(path, "status", "--porcelain", "--untracked-files=no")
    return [l for l in out.splitlines() if l.strip()] if rc == 0 else ["(git status failed)"]


def hidden_edits(path):
    """Files git status skips because of assume-unchanged or skip-worktree."""
    rc, out = git(path, "ls-files", "-v")
    if rc != 0:
        return ["(git ls-files failed)"]
    return [l[2:] for l in out.splitlines() if l[:1].islower() or l[:1] == "S"]


def untracked(path):
    """Untracked files, minus symlinks, which setup scripts create and which hold no data."""
    rc, out = git(path, "ls-files", "--others", "--exclude-standard", "-z")
    if rc != 0:
        return ["(git ls-files failed)"], []
    files, links = [], []
    for f in filter(None, out.split("\0")):
        (links if os.path.islink(os.path.join(path, f)) else files).append(f)
    return files, links


def contains_path(entry, paths):
    padded = "/" + entry.strip("/") + "/"
    return any(f"/{p}/" in padded for p in paths)


def ignored_kind(e):
    """'build' for output and env copies, 'scratch' for agent scratch, else 'keep'."""
    parts = e.rstrip("/").split("/")
    name = parts[-1]
    if (
        any(p in BUILD_DIRS for p in parts)
        or name in BUILD_NAMES
        or name.endswith(BUILD_SUFFIXES)
        or contains_path(e, BUILD_PATHS)
        or (name.startswith(ENV_PREFIXES) and not e.endswith("/"))
    ):
        return "build"
    if parts[0] in SCRATCH_DIRS or contains_path(e, SCRATCH_PATHS):
        return "scratch"
    return "keep"


def ignored(path):
    """Split ignored paths into (kept data, agent scratch). Build output and env copies go."""
    listing = ["ls-files", "--others", "--ignored", "--exclude-standard", "-z"]
    rc, out = git(path, *listing, "--directory")
    if rc != 0:
        return ["(git ls-files failed)"], []
    keep, scratch = [], []
    for e in filter(None, out.split("\0")):
        kind = ignored_kind(e)
        if kind == "keep" and e.endswith("/"):
            # git folds a folder whose files are all ignored into one entry, so look inside.
            rc, files = git(path, *listing, "--", e)
            kinds = {f: ignored_kind(f) for f in filter(None, files.split("\0"))}
            if rc == 0 and set(kinds.values()) <= {"build", "scratch"}:
                kind = "scratch" if "scratch" in kinds.values() else "build"
            elif rc == 0:
                e = next(f for f, k in kinds.items() if k == "keep")
        if kind != "build":
            (scratch if kind == "scratch" else keep).append(e)
    return keep, scratch


def nested_repo(path):
    """A clone inside an ignored folder, which git status can't see into."""
    rc, out, _ = run(
        ["find", path, "-mindepth", "2", "-name", ".git", "-print", "-quit"], timeout=900
    )
    return out.strip() if rc == 0 else "(find failed)"


def unfinished_op(path):
    rc, out = git(path, "rev-parse", "--absolute-git-dir")
    if rc != 0:
        return "(git rev-parse failed)"
    return next((op for op in UNFINISHED_OPS if (Path(out.strip()) / op).exists()), None)


def head(path):
    return git(path, "rev-parse", "HEAD")[1].strip()


def in_use(rp, ctx):
    """Why a T3 project, thread, or process is using the worktree, or None."""
    if any(inside(r, rp) for r in ctx["project_roots"]):
        return "a T3 project points inside it"
    uses = ctx["uses"].get(rp, [])
    for state in ("running", "pinned", "open"):
        title = next((t for t, s in uses if s == state), None)
        if title is not None:
            return f'{state} thread "{title}"'
    if any(inside(c, rp) for c in ctx["cwds"]):
        return "a process is running inside it"
    return None


def judge(wt, ctx):
    """Return (remove?, reason)."""
    path, repo = wt["path"], wt["repo"]
    rp = real(path)
    states = {s for _, s in ctx["uses"].get(rp, [])}

    allowed = [real(r) for r in WORKTREE_ROOTS] + [real(Path(repo) / ".claude/worktrees")]
    if not any(strictly_inside(rp, r) for r in allowed):
        return False, "outside the agent worktree folders"
    if wt.get("locked"):
        return False, "locked"
    busy = in_use(rp, ctx)
    if busy:
        return False, busy
    op = unfinished_op(path)
    if op:
        return False, f"a git operation is paused in it, {op}"
    nested = [o for o in ctx["all_paths"] if strictly_inside(o, rp)]
    if nested:
        return False, f"contains another checkout, {short(nested[0])}"
    edits = tracked_edits(path)
    if edits:
        return False, f"{len(edits)} uncommitted edits"
    hidden = hidden_edits(path)
    if hidden:
        return False, f"{len(hidden)} files git status skips, such as {hidden[0]}"
    loose, _ = untracked(path)
    if loose:
        return False, f"{len(loose)} untracked files, such as {loose[0]}"
    keep, scratch = ignored(path)
    if keep:
        return False, f"ignored files that aren't build output, such as {keep[0]}"
    if wt.get("detached") and not git(path, "for-each-ref", "--contains", "HEAD", "--count=1")[1].strip():
        return False, "detached HEAD with commits no branch has"
    inner = nested_repo(path)
    if inner:
        return False, f"contains a nested git repo, {short(inner)}"

    extra = f", and its scratch {', '.join(scratch)}" if scratch else ""
    if states == {"archived"}:
        return True, "its threads are archived" + extra
    if time.time() - last_activity(path) < RECENT_SECONDS:
        return False, "used in the last day"

    main = ctx["main"][repo]
    if main and git(path, "merge-base", "--is-ancestor", "HEAD", main)[0] == 0:
        return True, f"everything in it is on {main[7:]}" + extra
    branch = wt["branch"][11:] if isinstance(wt.get("branch"), str) else ""
    prs = ctx["prs"][repo]
    if prs is None and branch:
        return False, "couldn't check its PR this run"
    pr = prs.get(branch) if branch else None
    if pr and pr["state"] in ("MERGED", "CLOSED"):
        h = head(path)
        if h == pr["headRefOid"] or git(path, "merge-base", "--is-ancestor", h, pr["headRefOid"])[0] == 0:
            return True, f"PR #{pr['number']} {pr['state'].lower()}" + extra
        return False, f"has commits PR #{pr['number']} didn't include"
    if pr:
        return False, f"PR #{pr['number']} open"
    if "settled" in states:
        return False, "not merged, no PR, thread settled. Archive the thread to let it go"
    return False, "not merged and no PR"


def remove(wt, ctx):
    """Check again, then let git refuse anything that changed.

    The slow file scans run first and the T3 and process checks last, so the
    gap before removal is short. Nothing closes it fully, because the tools
    that open worktrees take no lock this script could share.
    """
    ok, why = judge(wt, ctx)
    if not ok:
        return f"changed since the check, now {why}"
    try:
        fresh = dict(ctx)
        fresh["uses"], fresh["project_roots"] = t3_state()
        fresh["cwds"] = process_cwds()
    except Stop as e:
        return f"stopped, {e}"
    busy = in_use(real(wt["path"]), fresh)
    if busy:
        return f"changed since the check, now {busy}"
    if head(wt["path"]) != wt["head"]:
        return "HEAD moved since the check"
    _, links = untracked(wt["path"])
    for f in links:
        link = os.path.join(wt["path"], f)
        if os.path.islink(link):
            os.unlink(link)
    rc, _, err = run(["git", "-C", wt["repo"], "worktree", "remove", wt["path"]], timeout=900)
    if rc != 0:
        return "git refused: " + (err.strip().splitlines() or ["no message"])[-1]
    if os.path.exists(wt["path"]):
        return "git left the folder behind"
    return None


def leftover_folders(all_paths):
    found = []
    for root in WORKTREE_ROOTS:
        if root.is_dir():
            for d in root.glob("*/*"):
                if d.is_dir() and not d.is_symlink() and not any(inside(o, str(d)) for o in all_paths):
                    found.append(str(d))
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--apply", action="store_true", help="remove what passes; default is a dry run")
    args = ap.parse_args()

    before = free_gb()
    try:
        uses, project_roots = t3_state()
        cwds = process_cwds()
    except Stop as e:
        print(f"Worktree cleanup stopped before removing anything: {e}")
        return 2
    repos = discover_repos(project_roots)
    notes, wts = [], []
    ctx = dict(uses=uses, project_roots=project_roots, cwds=cwds, prs={}, main={})
    for repo in repos.values():
        ctx["main"][repo] = refresh_default_branch(repo, notes)
        ctx["prs"][repo] = pr_states(repo, notes)
        for w in list_worktrees(repo):
            if not w.get("bare"):
                w["path"], w["repo"] = w["worktree"], repo
                wts.append(w)

    present = [w for w in wts if os.path.isdir(w["path"])]
    missing = [w for w in wts if not os.path.isdir(w["path"])]
    ctx["all_paths"] = [real(w["path"]) for w in present] + [real(r) for r in repos.values()]

    removed, held, failed = [], [], []
    for w in sorted(present, key=lambda w: w["path"]):
        w["head"] = head(w["path"])
        ok, why = judge(w, ctx)
        if not ok:
            held.append((w["path"], why))
        elif not args.apply:
            removed.append((w["path"], why))
        else:
            err = remove(w, ctx)
            (failed if err else removed).append((w["path"], err or why))

    if args.apply:
        for root in WORKTREE_ROOTS:
            for d in root.iterdir() if root.is_dir() else []:
                if d.is_dir() and not d.is_symlink() and set(os.listdir(d)) <= {".DS_Store"}:
                    if (d / ".DS_Store").exists():
                        (d / ".DS_Store").unlink()
                    d.rmdir()

    after = free_gb()
    host = socket.gethostname().split(".")[0]
    mode = "applied" if args.apply else "dry run, nothing removed"
    print(f"Worktree cleanup on {host}, {time.strftime('%Y-%m-%d %H:%M')} ({mode})")
    print(f"Free space: {before:.1f} GB before, {after:.1f} GB after")
    print(f"\n{'Removed' if args.apply else 'Would remove'} ({len(removed)}):")
    for p, why in removed:
        print(f"  {short(p)}  {why}")
    if failed:
        print(f"\nFailed ({len(failed)}):")
        for p, why in failed:
            print(f"  {short(p)}  {why}")
    print(f"\nHeld ({len(held)}):")
    for p, why in held:
        print(f"  {short(p)}  {size_of(p)}  {why}")
    if missing:
        print(f"\nRegistered worktrees whose folder is gone, left registered ({len(missing)}):")
        for w in missing:
            print(f"  {short(w['path'])}  run `git worktree prune` in {short(w['repo'])} if it isn't on an unplugged drive")
    leftovers = leftover_folders([real(w["path"]) for w in present])
    if leftovers:
        print(f"\nFolders git doesn't know as worktrees, left alone ({len(leftovers)}):")
        for p in leftovers:
            print(f"  {short(p)}  {size_of(p)}")
    if notes:
        print()
        for n in notes:
            print(n)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
